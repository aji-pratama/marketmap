import { CryptoCoin, Currency } from '../types/crypto';

export const CURRENCY_RATES: Record<Currency, { symbol: string; rate: number; prefix: boolean }> = {
  IDR: { symbol: 'Rp', rate: 1, prefix: true },
  USD: { symbol: '$', rate: 1 / 16200, prefix: true },
  EUR: { symbol: '€', rate: 1 / 17500, prefix: true },
};

export function formatPrice(priceIdr: number, currency: Currency = 'IDR'): string {
  const conf = CURRENCY_RATES[currency] || CURRENCY_RATES.IDR;
  const converted = priceIdr * conf.rate;

  let formatted = '';
  if (currency === 'IDR') {
    formatted = Math.round(converted).toLocaleString('id-ID');
    return `${conf.symbol} ${formatted}`;
  } else {
    if (converted >= 1000) {
      formatted = converted.toLocaleString('en-US', { maximumFractionDigits: 2, minimumFractionDigits: 2 });
    } else if (converted >= 1) {
      formatted = converted.toFixed(2);
    } else {
      formatted = converted.toFixed(4);
    }
    return conf.prefix ? `${conf.symbol}${formatted}` : `${formatted} ${conf.symbol}`;
  }
}

export function formatNumber(num: number, currency: Currency = 'IDR', compact = true): string {
  const conf = CURRENCY_RATES[currency] || CURRENCY_RATES.IDR;
  const converted = num * conf.rate;

  if (compact) {
    if (currency === 'IDR') {
      if (converted >= 1e12) return `${conf.symbol} ${(converted / 1e12).toFixed(1)}T`;
      if (converted >= 1e9) return `${conf.symbol} ${(converted / 1e9).toFixed(1)}M`;
      if (converted >= 1e6) return `${conf.symbol} ${(converted / 1e6).toFixed(1)}Jt`;
      if (converted >= 1e3) return `${conf.symbol} ${(converted / 1e3).toFixed(1)}Rb`;
    } else {
      if (converted >= 1e12) return `${conf.symbol}${(converted / 1e12).toFixed(2)}T`;
      if (converted >= 1e9) return `${conf.symbol}${(converted / 1e9).toFixed(2)}B`;
      if (converted >= 1e6) return `${conf.symbol}${(converted / 1e6).toFixed(2)}M`;
      if (converted >= 1e3) return `${conf.symbol}${(converted / 1e3).toFixed(1)}K`;
    }
  }

  return currency === 'IDR'
    ? `${conf.symbol} ${Math.round(converted).toLocaleString('id-ID')}`
    : `${conf.symbol}${converted.toLocaleString('en-US', { maximumFractionDigits: 0 })}`;
}

export function formatPercent(val: number): string {
  const sign = val > 0 ? '+' : '';
  return `${sign}${val.toFixed(2)}%`;
}

